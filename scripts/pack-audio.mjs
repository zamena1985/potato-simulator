// Embed the small recordings so Web Audio also works when START.cmd opens file://.
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url),samples={};
for(const name of ['cuckoo','dog'])samples[name]=(await readFile(new URL(`assets/${name}.ogg`,root))).toString('base64');
await writeFile(new URL('assets/ambient-samples.js',root),'/* Generated by scripts/pack-audio.mjs. Recording credits: assets/CREDITS.md. */\nwindow.SummerSamples='+JSON.stringify(samples)+';\n');
